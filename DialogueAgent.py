    def __init__(self):
        self.nlu = SimpleNLU()
        self.stateUpdate = SimpleStateUpdater()
        self.dialogDecision = DialogueDecider()
        self.nlg = SimpleGenerator()

    def _dialoguePipeline(
        self, inputText: str, state: DialogueState, last_action: DialogueAct
    ) -> Tuple[str, DialogueState, DialogueAct]:

        inputAction = self.nlu.parse(inputText, last_action)
        state = self.stateUpdate.update(state, inputAction)
        systemAction = self.dialogDecision.actOn(state)
        output = self.nlg.generate(systemAction)
        return output, state, systemAction

